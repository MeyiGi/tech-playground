# УСЛОВИЕ:
# Нужно составить рацион из двух продуктов
# с минимальной стоимостью.
#
# ДАНО:
#
#               Продукт A    Продукт B
# Цена             40 сом       30 сом
# Белки              2            1
# Витамины           1            3
#
# Человеку необходимо минимум:
# 8 единиц белков
# 9 единиц витаминов
#
# НАЙТИ:
# x - количество продукта A
# y - количество продукта B
#
# Минимизировать: Z = 40x + 30y
#
# ОГРАНИЧЕНИЯ:
# 2x + y >= 8
# x + 3y >= 9
# x >= 0, y >= 0
#
# МЕТОД: Графический метод оптимизации
# ==========================================


x = (8 * 3 - 9) / 5
y = 8 - 2 * x

# Три угловые точки
points = [(0, 8), (9, 0), (x, y)]

best = float("inf")

for a, b in points:
    price = 40 * a + 30 * b

    if price < best:
        best = price
        answer = (a, b)

print("Рацион:", answer)
print("Стоимость:", best)